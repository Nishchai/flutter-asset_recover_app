import 'dart:math';

/// The contextual detail of an audit entry — the `activityContext` block of the
/// platform Audit Log contract.
///
/// The app's own context is the entity the activity acted on ([entityType] /
/// [entityId], e.g. `battery` / `BP123456`); everything else a call site wants
/// to record (ticket id, chosen outcome, section name, …) rides in [details]
/// and is flattened into the same JSON object, so a context serializes as
/// `{"entityType": "battery", "entityId": "BP1", "outcome": "recovered"}`.
class ActivityContext {
  const ActivityContext({
    this.entityType,
    this.entityId,
    this.details = const {},
  });

  /// What kind of thing the activity acted on — `battery`, `ticket`, …
  final String? entityType;

  /// The identifier of that thing (BP id, ticket id, …).
  final String? entityId;

  /// Free-form extras, merged into the serialized context alongside the two
  /// named fields.
  final Map<String, dynamic> details;

  bool get isEmpty =>
      (entityType == null || entityType!.isEmpty) &&
      (entityId == null || entityId!.isEmpty) &&
      details.isEmpty;

  factory ActivityContext.fromJson(Map<String, dynamic> json) {
    final rest = Map<String, dynamic>.from(json)
      ..remove('entityType')
      ..remove('entityId');
    return ActivityContext(
      entityType: json['entityType'] as String?,
      entityId: json['entityId'] as String?,
      details: rest,
    );
  }

  Map<String, dynamic> toJson() => {
        if (entityType != null) 'entityType': entityType,
        if (entityId != null) 'entityId': entityId,
        ...details,
      };
}

/// A single audit-log entry (item 15 / PRD §5.1.3, §7.A — status transitions,
/// approvals and other state-changing actions must be logged with a timestamp
/// and user). The full audit dashboard lives on the coordinator Web App; this
/// mobile app is only responsible for emitting these events.
///
/// Mirrors the platform Audit Log API request body field-for-field (`POST
/// /AuditLog` on the platform host — see `api_endpoints.json` `audit.log` and
/// `EnvironmentConfig.auditLogBaseUrl`), so [toJson] IS the wire payload:
///
/// ```json
/// {
///   "transactionId": "…", "userId": "SUNMU00002340", "userName": "…",
///   "activityStartDate": 1786290112123, "activityEndDate": 1786290112123,
///   "userActivity": "outcome_submitted",
///   "appName": "Asset Recovery", "appVersion": "1.0.3",
///   "status": "SUCCESS",
///   "activityContext": { … }
/// }
/// ```
///
/// [toJson]/[fromJson] round-trip losslessly because the offline queue persists
/// a failed send as this exact JSON and replays it later (see
/// `AuditLogService`).
class AuditEvent {
  AuditEvent({
    required this.transactionId,
    required this.userId,
    required this.userActivity,
    required this.activityStartDate,
    this.userName,
    this.activityEndDate,
    this.appName,
    this.appVersion,
    this.status,
    this.activityContext,
  });

  /// Correlation id for this one activity, unique per event. Generated by
  /// [newTransactionId] when the caller has no id of its own to correlate with.
  final String transactionId;

  /// The signed-in agent — the `commonLogin` `userId` (`SUNMU…` series), the
  /// same id every other request is scoped by.
  final String userId;

  final String? userName;

  /// When the activity began, and when it finished. Both are IST wall-clock
  /// instants (see `nowIst`); for the instantaneous actions the app logs the
  /// two are usually the same moment.
  ///
  /// [activityEndDate] is nullable here but never serialized as null — the API
  /// types both fields as a non-nullable `System.Int64`, so an open-ended
  /// activity is sent with its end equal to its start (see [toJson]).
  final DateTime activityStartDate;
  final DateTime? activityEndDate;

  /// What the user did, e.g. `call_customer_submitted`,
  /// `visit_bp_location_submitted`, `visit_customer_address_submitted`,
  /// `outcome_submitted`, `customer_details_updated`, `call_started`,
  /// `login_success`, `logout`.
  final String userActivity;

  final String? appName;
  final String? appVersion;

  /// Outcome of the activity — [statusSuccess] / [statusFailure].
  final String? status;

  final ActivityContext? activityContext;

  static const String statusSuccess = 'SUCCESS';
  static const String statusFailure = 'FAILURE';

  factory AuditEvent.fromJson(Map<String, dynamic> json) {
    final context = json['activityContext'];
    return AuditEvent(
      transactionId: json['transactionId'] as String? ?? newTransactionId(),
      userId: json['userId'] as String? ?? '',
      userName: json['userName'] as String?,
      activityStartDate:
          parseTimestamp(json['activityStartDate']) ?? DateTime.now(),
      activityEndDate: parseTimestamp(json['activityEndDate']),
      userActivity: json['userActivity'] as String? ?? '',
      appName: json['appName'] as String?,
      appVersion: json['appVersion'] as String?,
      status: json['status'] as String?,
      activityContext: context is Map
          ? ActivityContext.fromJson(Map<String, dynamic>.from(context))
          : null,
    );
  }

  Map<String, dynamic> toJson() => {
        'transactionId': transactionId,
        'userId': userId,
        'userName': userName,
        'activityStartDate': formatTimestamp(activityStartDate),
        // Never null: the contract types this as a non-nullable Int64, and an
        // activity with no recorded end is a zero-length one at its start.
        'activityEndDate': formatTimestamp(activityEndDate ?? activityStartDate),
        'userActivity': userActivity,
        'appName': appName,
        'appVersion': appVersion,
        'status': status,
        'activityContext': activityContext?.toJson(),
      };

  /// Epoch **milliseconds** of the IST wall clock, e.g. `1786290112123`.
  ///
  /// The API types both date fields as `System.Int64` and rejects anything else
  /// (an ISO string comes back as `Error converting value … to type
  /// 'System.Int64'`), so the payload carries a number, not text.
  ///
  /// The app's timestamps come from `nowIst()`, which is a UTC-*flagged*
  /// [DateTime] whose fields already read as Indian local time. Taking
  /// [DateTime.millisecondsSinceEpoch] of that value therefore encodes the IST
  /// wall clock — numerically the same instant the old zone-less ISO string
  /// encoded, so entries keep reading as IST in the dashboard exactly as they
  /// did before. If the platform instead renders these longs in IST itself,
  /// this is the one place to subtract `istOffset`.
  static int? formatTimestamp(DateTime? value) =>
      value?.millisecondsSinceEpoch;

  /// Inverse of [formatTimestamp] — used when the offline queue replays a
  /// persisted event.
  ///
  /// Accepts the epoch number [formatTimestamp] writes, and still reads the
  /// zone-less ISO strings written by earlier builds so entries already sitting
  /// in the queue replay instead of being dropped. Either form comes back as
  /// the same UTC-flagged IST instant it was written from (parsing a zone-less
  /// string naively would re-interpret it in the device's zone and shift it).
  static DateTime? parseTimestamp(Object? raw) {
    if (raw is num) {
      return DateTime.fromMillisecondsSinceEpoch(raw.toInt(), isUtc: true);
    }
    if (raw is! String || raw.isEmpty) return null;
    final asEpoch = int.tryParse(raw);
    if (asEpoch != null) {
      return DateTime.fromMillisecondsSinceEpoch(asEpoch, isUtc: true);
    }
    final hasZone =
        raw.endsWith('Z') || RegExp(r'[+-]\d{2}:?\d{2}$').hasMatch(raw);
    return DateTime.tryParse(hasZone ? raw : '${raw}Z')?.toUtc();
  }

  static final _rand = Random();

  /// A fresh correlation id: RFC-4122 v4 shape, generated locally (the app has
  /// no uuid dependency and the value only has to be unique, not cryptographic).
  static String newTransactionId() {
    final bytes = List<int>.generate(16, (_) => _rand.nextInt(256));
    bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
    bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 1
    final hex = bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-'
        '${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}';
  }
}
